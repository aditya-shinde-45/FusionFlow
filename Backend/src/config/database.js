// Database access abstraction layer
export const db = {
  // Collection access
  collection(name) {
    if (!store[name]) {
      store[name] = [];
    }
    return {
      async find(predicate = () => true) {
        return store[name].filter(predicate);
      },
      async findOne(predicate) {
        return store[name].find(predicate) || null;
      },
      async findById(id) {
        return store[name].find((item) => item.id === id || item.code === id) || null;
      },
      async insert(item) {
        const record = { id: item.id || generateUUID(), createdAt: new Date().toISOString(), ...item };
        store[name].unshift(record);
        return record;
      },
      async update(predicate, updates) {
        const item = store[name].find(predicate);
        if (!item) return null;
        Object.assign(item, updates, { updatedAt: new Date().toISOString() });
        return item;
      },
      async updateById(id, updates) {
        return this.update((item) => item.id === id || item.code === id, updates);
      },
      async delete(predicate) {
        const index = store[name].findIndex(predicate);
        if (index === -1) return false;
        store[name].splice(index, 1);
        return true;
      },
      async deleteById(id) {
        return this.delete((item) => item.id === id || item.code === id);
      },
      async count(predicate = () => true) {
        return store[name].filter(predicate).length;
      },
    };
  },

  // Reset store for tests
  reset() {
    // deep reset can be called in test hooks
  },

  // Health check
  async ping() {
    return {
      status: "healthy",
      tablesCount: Object.keys(store).length,
      recordsCount: Object.values(store).reduce((sum, list) => sum + list.length, 0),
      supabaseConfigured: !!supabaseClient,
    };
  },

  // Supabase direct client if needed
  supabase: supabaseClient,
};

